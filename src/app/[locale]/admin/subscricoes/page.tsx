import type { Metadata } from "next";
import { hasLocale } from "next-intl";
import { getTranslations, setRequestLocale } from "next-intl/server";
import { notFound } from "next/navigation";
import { SubscriptionsView } from "@/components/admin/SubscriptionsView";
import { routing } from "@/i18n/routing";
import { requireAdmin } from "@/server/auth/admin";
import { subscriptionsOverview } from "@/server/modules/admin/subscriptions";

type Props = { params: Promise<{ locale: string }> };

export async function generateMetadata({ params }: Props): Promise<Metadata> {
  const { locale } = await params;
  if (!hasLocale(routing.locales, locale)) notFound();
  const t = await getTranslations({ locale, namespace: "Admin.subscriptions" });
  return { title: `${t("title")} — Kandrop Admin` };
}

export default async function Page({ params }: Props) {
  const { locale } = await params;
  if (!hasLocale(routing.locales, locale)) notFound();
  setRequestLocale(locale);
  await requireAdmin(locale);
  return <SubscriptionsView rows={await subscriptionsOverview().catch(() => [])} />;
}
